// Generates every logo asset from one hand-drawn SVG definition.
// Run: npm run brand   (needs the "sharp" dev dependency)
import sharp from "sharp";
import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const pub = path.join(root, "public");
const brand = path.join(pub, "brand");
const app = path.join(root, "src", "app");
mkdirSync(brand, { recursive: true });

// Geometry on a 512 grid: three rounded bars narrowing into a droplet.
const MARK = `
  <rect x="86" y="94" width="340" height="52" rx="26"/>
  <rect x="125" y="170" width="262" height="42" rx="21"/>
  <rect x="183" y="235" width="146" height="42" rx="21"/>
  <path d="M256 295C270.5 316.5 301 345.5 301 373A45 45 0 1 1 211 373C211 345.5 241.5 316.5 256 295Z"/>`;

const gradient = (id) => `
  <linearGradient id="${id}" x1="100" y1="90" x2="330" y2="420" gradientUnits="userSpaceOnUse">
    <stop offset="0" stop-color="#2F5BEA"/>
    <stop offset="0.5" stop-color="#2489E0"/>
    <stop offset="1" stop-color="#12B5A6"/>
  </linearGradient>`;

/** Mark only, transparent background, square viewBox with breathing room. */
const markSvg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="80 80 352 352" role="img" aria-label="Lumen">
  <defs>${gradient("lumen-g")}</defs>
  <g fill="url(#lumen-g)">${MARK}</g>
</svg>
`;

/** App tile: white rounded square with a hairline, mark centred. */
const tileSvg = (opts = {}) => {
  const { radius = 112, inset = 0, border = true, full = false, scale = 1 } = opts;
  const s = 512 - inset * 2;
  const t = `translate(256 256) scale(${scale}) translate(-256 -256)`;
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512">
  <defs>${gradient("lumen-g")}</defs>
  ${
    full
      ? `<rect width="512" height="512" fill="#FFFFFF"/>`
      : `<rect x="${inset}" y="${inset}" width="${s}" height="${s}" rx="${radius}" fill="#FFFFFF"/>
  ${border ? `<rect x="${inset + 4}" y="${inset + 4}" width="${s - 8}" height="${s - 8}" rx="${radius - 4}" fill="none" stroke="#E3E7EE" stroke-width="6"/>` : ""}`
  }
  <g fill="url(#lumen-g)" transform="${t}">${MARK}</g>
</svg>
`;
};

writeFileSync(path.join(brand, "lumen-mark.svg"), markSvg);
writeFileSync(path.join(brand, "lumen-icon.svg"), tileSvg());
// Next.js picks these up as the site icon automatically.
writeFileSync(path.join(app, "icon.svg"), tileSvg({ inset: 0, radius: 112, scale: 1.12 }));

async function png(svg, size, file) {
  const buf = await sharp(Buffer.from(svg), { density: 384 }).resize(size, size).png({ compressionLevel: 9 }).toBuffer();
  if (file) writeFileSync(file, buf);
  return buf;
}

// PWA icons
await png(tileSvg(), 192, path.join(brand, "icon-192.png"));
await png(tileSvg(), 512, path.join(brand, "icon-512.png"));
// Maskable: full-bleed background, mark inside the 80% safe zone.
await png(tileSvg({ full: true, scale: 0.78 }), 512, path.join(brand, "icon-maskable-512.png"));
// Apple touch icon: iOS applies its own rounded mask, so no transparency.
await png(tileSvg({ full: true, scale: 0.92 }), 180, path.join(app, "apple-icon.png"));
// Email logo and small mark rasters
const emailLogo = await png(tileSvg({ border: true }), 96, path.join(brand, "lumen-mark-96.png"));
await png(markSvg, 256, path.join(brand, "lumen-mark-256.png"));

// favicon.ico with 16, 32 and 48 px PNG frames
const frames = await Promise.all([16, 32, 48].map((s) => png(tileSvg({ scale: 1.12 }), s)));
const header = Buffer.alloc(6);
header.writeUInt16LE(0, 0);
header.writeUInt16LE(1, 2);
header.writeUInt16LE(frames.length, 4);
let offset = 6 + frames.length * 16;
const entries = frames.map((buf, i) => {
  const size = [16, 32, 48][i];
  const e = Buffer.alloc(16);
  e.writeUInt8(size, 0);
  e.writeUInt8(size, 1);
  e.writeUInt8(0, 2);
  e.writeUInt8(0, 3);
  e.writeUInt16LE(1, 4);
  e.writeUInt16LE(32, 6);
  e.writeUInt32LE(buf.length, 8);
  e.writeUInt32LE(offset, 12);
  offset += buf.length;
  return e;
});
writeFileSync(path.join(app, "favicon.ico"), Buffer.concat([header, ...entries, ...frames]));

// Logo for transactional emails, bundled into server code (works on serverless).
writeFileSync(
  path.join(root, "src", "lib", "server", "logo-data.ts"),
  `// Generated by scripts/build-brand.mjs. 96x96 PNG of the Lumen app tile.\nexport const LOGO_PNG_BASE64 =\n  "${emailLogo.toString("base64")}";\n`,
);

console.log("Brand assets written.");
